CARLA_AUDITWHEEL_VENV="${CARLA_WORK_ROOT}/auditwheel-venv"
CARLA_PATCHELF_PATH="/usr/bin/patchelf"

# uv reads these two values from its process environment.
export UV_PYTHON_INSTALL_DIR="${CARLA_PYTHON_ROOT}"
export UV_CACHE_DIR="${CARLA_WORK_ROOT}/uv-cache"
