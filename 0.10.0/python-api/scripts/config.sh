#!/usr/bin/env bash

# Fixed configuration for the CARLA 0.10.0 wheel build.

BUILD_CARLA_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
REPOSITORY_ROOT="$(cd -- "${BUILD_CARLA_DIR}/../.." && pwd)"

CARLA_VERSION="0.10.0"
CARLA_WHEEL_PLATFORM="manylinux_2_35_x86_64"
CARLA_PYTHON_VERSIONS=(3.10 3.11 3.12 3.13 3.14)
CARLA_CMAKE_VERSION="3.28.3"
CARLA_BUILD_VERSION="1.3.0"
CARLA_SCIKIT_BUILD_CORE_VERSION="0.11.6"
CARLA_WHEEL_VERSION="0.47.0"
CARLA_AUDITWHEEL_VERSION="6.7.0"
CARLA_BUILD_TOOLS_PYTHON_VERSION="3.10"
CARLA_AUDITWHEEL_PYTHON_VERSION="3.10"

CARLA_WORK_ROOT="${BUILD_CARLA_DIR}/.work"
CARLA_SOURCE_DIR="${CARLA_WORK_ROOT}/source"
CARLA_CMAKE_BUILD_ROOT="${CARLA_WORK_ROOT}/build"
CARLA_RAW_WHEEL_DIR="${CARLA_WORK_ROOT}/raw-wheels"
CARLA_OUTPUT_DIR="${BUILD_CARLA_DIR}/dist/wheels"
CARLA_VERIFY_ROOT="${CARLA_WORK_ROOT}/verify"
CARLA_PYTHON_ROOT="${CARLA_WORK_ROOT}/python"
CARLA_PYTHON_PACKAGE_ROOT="${CARLA_WORK_ROOT}/python-packages"
